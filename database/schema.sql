create table if not exists visitors (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  id_type text,
  id_number text,
  full_name text not null,
  gender text,
  company text,
  phone text,
  contact_person text,
  purpose text,
  vehicle_plate text,
  vehicle_type text,
  chip_serial text,
  note text,
  checkin_time timestamptz not null default now(),
  checkout_time timestamptz,
  photo_url text,
  qr_data text,
  other_purpose text,
  consent_given_at timestamptz,
  consent_notice_version text,
  consent_method text,
  cloud_id bigint unique,
  cloud_updated_at timestamptz,
  cloud_deleted_at timestamptz,
  cloud_photo_path text,
  cloud_synced_at timestamptz
);

alter table visitors add column if not exists cloud_id bigint;
alter table visitors add column if not exists cloud_updated_at timestamptz;
alter table visitors add column if not exists cloud_deleted_at timestamptz;
alter table visitors add column if not exists cloud_photo_path text;
alter table visitors add column if not exists cloud_synced_at timestamptz;

create unique index if not exists visitors_cloud_id_idx on visitors (cloud_id);

create index if not exists visitors_checkin_time_idx on visitors (checkin_time desc);
create index if not exists visitors_checkout_time_idx on visitors (checkout_time);
create index if not exists visitors_full_name_lower_idx on visitors (lower(full_name));
create index if not exists visitors_cloud_updated_at_idx on visitors (cloud_updated_at);

create table if not exists app_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);
