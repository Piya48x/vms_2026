create table if not exists public.visitors (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  id_type text,
  id_number text,
  full_name text not null,
  gender text,
  company text,
  phone text,
  contact_person text,
  purpose text,
  vehicle_plate text,
  vehicle_type text,
  chip_serial text,
  note text,
  checkin_time timestamptz not null default now(),
  checkout_time timestamptz,
  photo_url text,
  qr_data text,
  other_purpose text,
  consent_given_at timestamptz,
  consent_notice_version text,
  consent_method text,
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

alter table public.visitors add column if not exists updated_at timestamptz not null default now();
alter table public.visitors add column if not exists deleted_at timestamptz;

create index if not exists visitors_checkin_time_idx on public.visitors (checkin_time desc);
create index if not exists visitors_checkout_time_idx on public.visitors (checkout_time);
create index if not exists visitors_updated_at_idx on public.visitors (updated_at, id);
create index if not exists visitors_deleted_at_idx on public.visitors (deleted_at);

create or replace function public.set_visitor_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists visitors_set_updated_at on public.visitors;
create trigger visitors_set_updated_at
before update on public.visitors
for each row execute function public.set_visitor_updated_at();

alter table public.visitors enable row level security;

drop policy if exists "report users can read visitors" on public.visitors;
create policy "report users can read visitors"
on public.visitors for select
to authenticated
using (true);

drop policy if exists "report users can update visitors" on public.visitors;
create policy "report users can update visitors"
on public.visitors for update
to authenticated
using (true)
