drop policy if exists "report users can delete visitors" on public.visitors;
create policy "report users can delete visitors"
on public.visitors for delete
to authenticated
using (true);

grant select, update, delete on public.visitors to authenticated;

create or replace function public.get_visitor_summary()
returns table(today integer, staying integer, "outToday" integer, "all" integer)
language sql
stable
security invoker
set search_path = public
as $$
  select
    count(*) filter (
      where deleted_at is null
        and checkin_time >= date_trunc('day', now() at time zone 'Asia/Bangkok') at time zone 'Asia/Bangkok'
        and checkin_time < (date_trunc('day', now() at time zone 'Asia/Bangkok') + interval '1 day') at time zone 'Asia/Bangkok'
    )::integer as today,
    count(*) filter (where deleted_at is null and checkout_time is null)::integer as staying,
    count(*) filter (
      where deleted_at is null
        and checkout_time >= date_trunc('day', now() at time zone 'Asia/Bangkok') at time zone 'Asia/Bangkok'
        and checkout_time < (date_trunc('day', now() at time zone 'Asia/Bangkok') + interval '1 day') at time zone 'Asia/Bangkok'
    )::integer as "outToday",
    count(*) filter (where deleted_at is null)::integer as "all"
  from public.visitors;
$$;

grant execute on function public.get_visitor_summary() to authenticated;

